-- Міграція 039: тип рядка-джерела для переміщення (invoice_transfers.line_kind).
-- Розрізняє чи переміщення взяло товар зі звичайного рядка чи з обмінного
-- (line_kind='exchange') — потрібно щоб анотації "передано →"/"отримано від"
-- у RoutesPage коректно прикріплювались до правильного рядка, коли у виробу
-- одночасно є і звичайний, і обмінний рядок. Той самий патерн, що й міграція
-- 036 для invoice_lines.line_kind. Історичні записи (усі — переміщення
-- звичайних рядків, обмін раніше не можна було переміщувати) лишаються
-- 'normal' за замовчуванням.

ALTER TABLE invoice_transfers ADD COLUMN line_kind TEXT DEFAULT 'normal';
