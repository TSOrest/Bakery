-- Медіум-знахідка QA-аудиту: повідомлення "Маршрут із такою назвою вже
-- існує" (safe_commit conflict_msg) ніколи не спрацьовувало, бо унікального
-- обмеження на routes.name не було взагалі. Два маршрути з однаковою назвою
-- створювались без помилки. Перевірка реальної бази (2026-09) дублікатів
-- не виявила — індекс додається напряму, без дедуплікації.
CREATE UNIQUE INDEX IF NOT EXISTS idx_routes_name ON routes(name);

-- Той самий клас проблеми в client_groups: назва групи унікальна лише в
-- межах маршруту (та сама назва підгрупи цілком можлива на різних
-- маршрутах).
CREATE UNIQUE INDEX IF NOT EXISTS idx_client_groups_name_route ON client_groups(name, route_id);
