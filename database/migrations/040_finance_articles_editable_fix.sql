-- Міграція 040: виправлення бага в міграції 032.
--
-- Міграція 032 мала зробити editable=1 для типових операторських кас-статей,
-- але звірялась з НЕПРАВИЛЬНИМИ назвами: 'Виплата з каси' — такої статті
-- ніколи не існувало (справжня назва, створена міграцією 020, — 'Виведення
-- з каси'), а 'Списання' на БД, що вже пройшли канонізацію 020, є ІНШИМ,
-- окремим записом від новоствореної 'Списання боргу'. Через це два реальних
-- запити ('Оплата з каси', 'Виведення з каси') не отримали editable=1
-- взагалі, а старий запис 'Списання' міг лишитись не охопленим новим
-- 'Списання боргу'. Додатково — кілька канонічних статей (020) ніколи не
-- входили у список 032: 'Кредит обміну', 'Виручка магазину', 'Списання
-- магазину'.
--
-- Усі перелічені нижче статті — суми, які оператор вводить вручну щодня
-- (не автогенеровані системою, на відміну від 'Накладна', 'Початковий
-- баланс', 'Архівний залишок') — мають бути editable в межах поточного дня.

UPDATE finance_articles
   SET editable = 1
 WHERE name IN (
       'Оплата',
       'Внесення в касу',
       'Виведення з каси',
       'Оплата з каси',
       'Готівка водія',
       'Списання',
       'Списання боргу',
       'Кредит обміну',
       'Виручка магазину',
       'Списання магазину'
   );
